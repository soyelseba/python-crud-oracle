CREATE TABLE departamento (
    id_departamento NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    id_gerente NUMBER
);

CREATE TABLE empleado (
    id_empleado NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    direccion VARCHAR2(200),
    telefono VARCHAR2(30),
    correo_electronico VARCHAR2(150) NOT NULL UNIQUE,
    fecha_inicio_contrato DATE NOT NULL,
    salario NUMBER(12,2) NOT NULL,
    nombre_usuario VARCHAR2(80) NOT NULL UNIQUE,
    contrasena_hash VARCHAR2(255) NOT NULL,
    rol VARCHAR2(20) NOT NULL,
    area_administrada VARCHAR2(100),
    fecha_asignacion DATE,
    id_departamento NUMBER,
    CONSTRAINT fk_empleado_departamento FOREIGN KEY(id_departamento)
        REFERENCES departamento(id_departamento)
);

ALTER TABLE departamento ADD CONSTRAINT fk_departamento_gerente
    FOREIGN KEY(id_gerente) REFERENCES empleado(id_empleado);

CREATE TABLE proyecto (
    id_proyecto NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    descripcion VARCHAR2(500),
    fecha_inicio DATE NOT NULL,
    estado VARCHAR2(30) NOT NULL
);

CREATE TABLE empleado_proyecto (
    id_empleado NUMBER REFERENCES empleado(id_empleado),
    id_proyecto NUMBER REFERENCES proyecto(id_proyecto),
    CONSTRAINT pk_empleado_proyecto PRIMARY KEY(id_empleado, id_proyecto)
);

CREATE TABLE registro_tiempo (
    id_registro NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    horas_trabajadas NUMBER(5,2) NOT NULL,
    descripcion_tarea VARCHAR2(500),
    id_empleado NUMBER NOT NULL REFERENCES empleado(id_empleado),
    id_proyecto NUMBER NOT NULL REFERENCES proyecto(id_proyecto),
    CONSTRAINT ck_horas_trabajadas CHECK(horas_trabajadas > 0 AND horas_trabajadas <= 24)
);

CREATE TABLE reporte (
    id_reporte NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR2(100) NOT NULL,
    fecha_generacion DATE NOT NULL,
    contenido CLOB
);
